test('the end of an app is an overlay: what is finished, what is starting. It waits, a held G stops at it, Enter goes on, Esc loses nothing', { skip }, async () => {
  const { push, open, read, queue } = await rig()
  push('First', ['A', 'B', 'C', 'D'], null)
  push('Second', ['X', 'Y', 'Z'], null)
  const { page, errors } = await open('first')
  await page.keyboard.press('g')
  await draw(page, 0.2, 0.2, 0.5, 0.5)
  await page.keyboard.press('Meta+Enter')
  await settled(page)
  // Marks left on this one and moved past: answered as much as anything, and they go with the rest.
  await draw(page, 0.2, 0.2, 0.5, 0.5)
  await page.keyboard.press('ArrowRight')
  await settled(page)
  // Held, and pressed again and again: it stops at the overlay and goes no further.
  await page.keyboard.down('g')
  await page.keyboard.down('g')
  await page.keyboard.up('g')
  for (let i = 0; i < 4; i++) await page.keyboard.press('g')
  const words = await page.locator('#segment').innerText()
  assert.match(words, /Finished: First\. 4 answered, 2 with changes\./)
  assert.match(words, /You are now starting a new review:/)
  assert.match(words, /Second/)
  assert.match(words, /3 left/)
  assert.equal(await page.locator('#submitModal').isVisible(), false, 'no last step')
  assert.ok((await page.locator('#segment h1').boundingBox()).height >= 40, 'large')
  // It does not fade.
  await page.waitForTimeout(400)
  assert.equal(await page.locator('#segment').isVisible(), true)
  assert.match(await page.locator('#crumbs').innerText(), /First/, 'nothing has moved on')
  assert.equal((await queue('first')).screens.every(s => s.status !== 'waiting'), true, 'nothing left open')
  assert.equal(read('First').length, 4)
  assert.equal(read('Second').length, 0, 'nothing went through it')
  // Esc: back on the last screen. Nothing lost, and the way on comes back.
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#segment').isVisible(), false)
  assert.equal(await at(page), 4)
  await page.keyboard.press('g')
  await settled(page)
  assert.equal(await page.locator('#segment').isVisible(), true)
  assert.equal(read('First').length, 4)
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.getElementById('crumbs').textContent.includes('Second'))
  assert.equal(await at(page), 1)
  assert.equal(await page.locator('#segment').isVisible(), false)
  assert.deepEqual(errors, [])
})

