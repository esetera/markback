/**
 * The page itself, in a headless browser, each test on a server and a store of its own. The wizard has nothing to install, so
 * this borrows Playwright from elsewhere and is skipped without it:
 *
 *   REVIEW_PLAYWRIGHT_FROM=<a package.json with Playwright> REVIEW_CHROME=<a Chrome> npm test
 */
import assert from 'node:assert/strict'
import { execFileSync, spawn } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { createServer } from 'node:net'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { after, before, test } from 'node:test'
import { fileURLToPath } from 'node:url'
import { writePicture } from './helpers.mjs'

const from = process.env.REVIEW_PLAYWRIGHT_FROM
const skip = from ? false : 'set REVIEW_PLAYWRIGHT_FROM to a package.json that has Playwright'
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
let browser
/** A port nothing else is on: another wizard running here must not answer for this one. */
const freePort = () => new Promise((resolve, reject) => {
  const probe = createServer()
  probe.once('error', reject)
  probe.listen(0, '127.0.0.1', () => {
    const { port } = probe.address()
    probe.close(() => resolve(String(port)))
  })
})
const cleanups = []

before(async () => {
  if (skip) return
  const { chromium } = createRequire(from)('playwright')
  browser = await chromium.launch({ headless: true, ...(process.env.REVIEW_CHROME ? { executablePath: process.env.REVIEW_CHROME } : {}) })
})
after(async () => {
  await browser?.close()
  for (const clean of cleanups) clean()
})

/** A store and a server for one test. */
async function rig() {
  const home = mkdtempSync(join(tmpdir(), 'review-browser-'))
  const port = await freePort()
  // REVIEW_CHROME here is for driving these tests; a picture of an app is taken by the Chrome a person would have.
  const env = { ...process.env, REVIEW_HOME: home, REVIEW_PORT: port, REVIEW_CHROME: '' }
  // Wide: it fills the room, and what to check is the line under the bar. `tall` leaves room beside it.
  const picture = join(home, 'p.png')
  writePicture(picture, 1600, 900)
  const tall = join(home, 'tall.png')
  writePicture(tall, 500, 900)
  let server
  const start = async () => {
    server = spawn('node', [join(ROOT, 'server.mjs')], { env, stdio: 'ignore' })
    for (let i = 0; i < 100; i++) {
      if (await fetch(`http://127.0.0.1:${port}/api/queue`).then(r => r.ok, () => false)) break
      await new Promise(r => setTimeout(r, 100))
    }
  }
  const stop = () => new Promise(resolve => {
    server.once('exit', resolve)
    server.kill()
  })
  cleanups.push(() => {
    server.kill()
    rmSync(home, { recursive: true, force: true })
  })
  await start()
  const push = (app, screens, note = screen => `What ${screen} is about.`, extra = [], after = picture) => {
    for (const screen of screens) execFileSync('node', [join(ROOT, 'review.mjs'), 'push', '--app', app, '--screen', screen, '--after', after, ...(note ? ['--note', note(screen)] : []), ...extra], { env, stdio: 'ignore' })
  }
  const read = app => JSON.parse(execFileSync('node', [join(ROOT, 'review.mjs'), 'read', '--app', app, '--json'], { env, encoding: 'utf8' }))
  const queue = async slug => (await (await fetch(`http://127.0.0.1:${port}/api/queue`)).json()).apps.find(a => a.slug === slug)
  /** `undo` is how long an answer can be taken back. Long: it stays here. Short: it goes at once. */
  const open = async (app, { undo = 40, width = 1500, height = 960, colorScheme = 'light', seed = null } = {}) => {
    const context = await browser.newContext({ viewport: { width, height }, colorScheme })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    // A page with no icon: the browser asks for one and is told there is none.
    page.on('console', m => m.type() === 'error' && !/favicon/.test(m.location().url) && errors.push(`${m.text()} ${m.location().url}`))
    if (seed) await page.addInitScript(values => {
      for (const [key, value] of Object.entries(values)) if (localStorage.getItem(key) === null) localStorage.setItem(key, JSON.stringify(value))
    }, seed)
    await page.goto(`http://127.0.0.1:${port}/?undo=${undo}#${app}`)
    await page.locator('#canvas').waitFor()
    await page.waitForFunction(() => document.getElementById('canvas').width > 300)
    return { page, errors, url: page.url() }
  }
  const clear = app => execFileSync('node', [join(ROOT, 'review.mjs'), 'clear', '--app', app], { env, stdio: 'ignore' })
  return { push, read, queue, open, home, port, env, start, stop, clear, tall }
}

const at = async page => Number(/Screen (\d+) of/.exec(await page.locator('#overall').getAttribute('title'))[1])
const settled = page => page.waitForTimeout(90)
const waitFor = async get => {
  for (let i = 0; i < 100; i++) {
    const got = get()
    if (got) return got
    await new Promise(r => setTimeout(r, 50))
  }
  throw new Error('It did not come.')
}
const draw = async (page, x1, y1, x2, y2) => {
  const b = await page.locator('#canvas').boundingBox()
  await page.mouse.move(b.x + b.width * x1, b.y + b.height * y1)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width * x2, b.y + b.height * y2, { steps: 4 })
  await page.mouse.up()
  await page.waitForTimeout(40)
}
const startDrawing = async page => {
  const b = await page.locator('#canvas').boundingBox()
  await page.mouse.move(b.x + b.width * 0.2, b.y + b.height * 0.2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width * 0.5, b.y + b.height * 0.5, { steps: 3 })
}
/** Pixels of what is drawn on the canvas: nothing is drawn where it is clear. */
const inked = page => page.evaluate(() => {
  const c = document.getElementById('canvas')
  const { data } = c.getContext('2d').getImageData(0, 0, c.width, c.height)
  let n = 0
  for (let i = 3; i < data.length; i += 4) if (data[i]) n++
  return n
})
const saved = (page, app, id, round = 1) => page.evaluate(key => JSON.parse(localStorage.getItem(key) || 'null'), `review:${app}/${id}/${round}`)
const sizes = page => page.evaluate(() => {
  const box = document.getElementById('scroller')
  const r = box.getBoundingClientRect()
  return { w: r.width, h: r.height, cut: box.scrollWidth > box.clientWidth + 1 || box.scrollHeight > box.clientHeight + 1 }
})

